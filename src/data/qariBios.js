/**
 * Returns a unique bio, title, and style attributes object for any given reciter
 * @param {object} reciter
 * @returns {object} { bio, title, style, tags }
 */
export function getQariUniqueAttributes(reciter) {
  if (!reciter || !reciter.name) {
    return {
      title: 'Renowned Quran Reciter',
      style: 'Serene & Devotional Recitation',
      bio: 'A distinguished Quran reciter known for serene, heartfelt recitations listened to by believers worldwide.',
      tags: ['Quran Reciter', 'Murattal']
    };
  }

  const lower = reciter.name.toLowerCase();

  // 1. Check exact unique matching Qari bios
  for (const [key, details] of Object.entries(UNIQUE_QARI_BIOS)) {
    if (lower.includes(key)) {
      return details;
    }
  }

  // 2. Generate custom unique attribute based on Qari's specific name & origin
  const country = reciter.country ? `from ${reciter.country}` : 'in the Islamic world';
  const name = reciter.name;

  return {
    title: `${country.charAt(0).toUpperCase() + country.slice(1)} Qari`,
    style: 'Clear & Melodious Tajweed',
    bio: `${name} is an esteemed Quran reciter ${country}. Celebrated for his distinct vocal timbre, steady pace, and beautiful adherence to the rules of Tajweed.`,
    tags: [reciter.country || 'Quran Reciter', 'Tajweed Mastery', 'Murattal']
  };
}

import {test,expect,_electron as electron} from '@playwright/test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
test('liquid glass is consistent in both themes, the player and accessible solid mode',async()=>{
  const profile=await fs.mkdtemp(path.join(os.tmpdir(),'quranly-glass-'));
  const env={...process.env,QURANLY_TEST_PROFILE:profile};delete env.ELECTRON_RUN_AS_NODE;
  const app=await electron.launch({args:['.'],env});
  try {
    const page=await app.firstWindow();
    const cdp=await page.context().newCDPSession(page);
    await cdp.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-transparency',value:'no-preference'}]});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.evaluate(()=>{localStorage.setItem('quranly_onboarded','true');localStorage.setItem('quranly_theme','dark');localStorage.setItem('quranly_player_nature_theme','acid');});
    await page.reload();
    await expect(page.locator('.daily-ayah-card')).toBeVisible();
    const material=locator=>locator.evaluate(el=>{const s=getComputedStyle(el);return {fill:s.backgroundColor,filter:s.backdropFilter,radius:s.borderRadius,shadow:s.boxShadow};});
    const card=await material(page.locator('.daily-ayah-card'));
    const mini=await material(page.locator('.mini-player'));
    expect(card.fill).toBe(mini.fill);expect(card.radius).toBe(mini.radius);expect(card.filter).toContain('blur');expect(card.shadow).not.toBe('none');
    expect(await page.locator('.app-container').evaluate(el=>getComputedStyle(el).backgroundImage)).toContain('linear-gradient');
    await page.screenshot({path:'test-results/glass-home-dark.png'});
    await page.getByRole('link',{name:'Settings',exact:true}).click();
    await page.getByRole('button',{name:/Sign In \/ Register Account/}).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    expect((await material(page.getByRole('dialog'))).filter).toContain('blur');
    await page.screenshot({path:'test-results/glass-account.png'});
    await page.getByRole('button',{name:'Close account'}).click();
    await page.getByRole('button',{name:'Light',exact:true}).click();
    expect((await material(page.locator('.mini-player'))).fill).not.toBe(mini.fill);
    await expect.poll(async()=> (await material(page.locator('.settings-group').first())).fill).toBe((await material(page.locator('.mini-player'))).fill);
    const selected=await page.getByRole('button',{name:'Light',exact:true}).evaluate(el=>({bg:getComputedStyle(el).backgroundColor,text:getComputedStyle(el).color}));
    expect(selected.bg).not.toBe(selected.text);
    await page.screenshot({path:'test-results/glass-settings-light.png'});
    await page.getByRole('button',{name:'Dark',exact:true}).click();
    await page.getByRole('button',{name:'Open full player',exact:true}).click();
    await expect(page.locator('.full-screen-player')).toHaveAttribute('data-player-background','acid');
    await expect(page.locator('.full-screen-player canvas')).toBeVisible();
    expect((await material(page.locator('.fs-main-controls'))).filter).toContain('blur');
    await expect(page.getByRole('button',{name:'Download',exact:true})).toBeVisible();
    const seek=await page.getByRole('slider',{name:'Seek recitation',exact:true}).boundingBox();
    expect(seek.y+seek.height).toBeLessThan(await page.evaluate(()=>innerHeight));
    await page.screenshot({path:'test-results/glass-player.png'});
    await cdp.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-transparency',value:'reduce'}]});
    expect(await page.evaluate(()=>matchMedia('(prefers-reduced-transparency:reduce)').matches)).toBe(true);
    expect((await material(page.locator('.fs-main-controls'))).filter).toBe('none');
    await cdp.detach();
    expect(errors).toEqual([]);
  } finally {await app.close();await fs.rm(profile,{recursive:true,force:true});}
});

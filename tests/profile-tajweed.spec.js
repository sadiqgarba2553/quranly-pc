import {test,expect,_electron as electron} from '@playwright/test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
test('reciter profiles contain photos, use silhouettes on failure, and Tajweed controls are readable and accessible',async()=>{
 const profile=await fs.mkdtemp(path.join(os.tmpdir(),'quranly-profile-ui-'));
 const env={...process.env,QURANLY_TEST_PROFILE:profile};delete env.ELECTRON_RUN_AS_NODE;
 const executablePath=process.env.QURANLY_TEST_EXE;
 const app=await electron.launch({executablePath,args:executablePath?[`--user-data-dir=${profile}`]:['.'],env});
 try{
  const page=await app.firstWindow();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.context().addInitScript(()=>{const Original=window.Audio;window.__guideAudios=[];window.Audio=function(...args){const a=new Original(...args);a.play=()=>Promise.resolve();const pause=a.pause.bind(a);a.pause=()=>{a.__paused=true;pause();};window.__guideAudios.push(a);return a;};});
  const reciters=['Mohammed Ayyub','Unknown Test Reciter','Ali Jaber'].map((name,i)=>({id:990+i,name,letter:name[0],moshaf:[{id:1,name:'Hafs',server:'https://example.test/audio/',surah_list:'1,18,36,55,67'}]}));
  await page.context().route('https://mp3quran.net/api/v3/**',route=>{const endpoint=new URL(route.request().url()).pathname.split('/').at(-1);return route.fulfill({json:{[endpoint]:endpoint==='reciters'?reciters:[]}});});
  await page.context().route('**/reciters/ali-jaber.jpg',r=>r.fulfill({status:404,body:''}));
  await page.context().route('https://api.alquran.cloud/v1/page/**',r=>r.fulfill({json:{code:200,data:{number:1,ayahs:[{number:1,numberInSurah:1,text:r.request().url().includes('quran-tajweed')?'[g[نّ] [n[ا] [i[م]':'بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ',surah:{number:1,name:'الفاتحة',englishName:'Al-Fatihah'},juz:1,page:1}]}}}));
  await page.context().route('https://api.quran.com/api/v4/verses/by_page/**',r=>r.fulfill({json:{verses:[]}}));
  await page.getByRole('button',{name:'Skip setup'}).click();
  await page.evaluate(()=>localStorage.setItem('quranly_theme','dark'));await page.reload();
  await page.getByRole('link',{name:'Reciters',exact:true}).click();
  const openProfile=name=>page.getByRole('button',{name:`View ${name} profile`,exact:true}).click();
  await openProfile('Mohammed Ayyub');
  await expect(page.getByRole('heading',{name:'Mohammed Ayyub',exact:true})).toBeVisible();
  const portrait=page.locator('.hero-qari-img');
  await expect.poll(()=>portrait.evaluate(el=>el.naturalWidth)).toBeGreaterThan(0);
  expect(await portrait.evaluate(el=>getComputedStyle(el).objectFit)).toBe('contain');
  const box=await portrait.boundingBox();expect(box.width).toBeLessThanOrEqual(240);expect(box.height).toBeLessThanOrEqual(240);
  await page.getByRole('button',{name:'Follow Qari',exact:true}).click();
  await expect(page.getByRole('button',{name:'Following Qari',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.screenshot({path:'test-results/reciter-profile-dark.png'});
  await page.getByRole('button',{name:'Back',exact:true}).click();
  await openProfile('Unknown Test Reciter');
  await expect(page.locator('.hero-qari-img')).toHaveAttribute('src',/reciter-silhouette\.svg$/);
  await page.screenshot({path:'test-results/reciter-profile-silhouette.png'});
  await page.getByRole('button',{name:'Back',exact:true}).click();await openProfile('Ali Jaber');
  await expect(page.locator('.hero-qari-img')).toHaveAttribute('src',/reciter-silhouette\.svg$/);
  await page.getByRole('button',{name:'Back',exact:true}).click();
  await page.getByRole('link',{name:'Read Quran',exact:true}).click();
  await page.getByRole('button',{name:'Interactive Tajweed & Pronunciation Guide',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Tajweed & pronunciation',exact:true});
  await expect(dialog).toBeVisible();
  expect(await dialog.locator('[role=tab]').count()).toBe(6);
  await dialog.getByRole('tab',{name:/Ghunnah/}).focus();await page.keyboard.press('ArrowRight');
  await expect(dialog.getByRole('tab',{name:/Qalqalah/})).toHaveAttribute('aria-selected','true');
  const play=dialog.getByRole('button',{name:'Play verse sample',exact:true});
  const colours=await play.evaluate(el=>({bg:getComputedStyle(el).backgroundColor,text:getComputedStyle(el).color}));expect(colours.bg).not.toBe(colours.text);
  await play.click();
  expect(await page.evaluate(()=>window.__guideAudios.some(a=>a.src.endsWith('/6222.mp3')))).toBe(true);
  await expect(dialog.getByRole('button',{name:'Stop sample',exact:true})).toBeVisible();
  await page.evaluate(()=>window.__guideAudios.find(a=>a.src.endsWith('/6222.mp3')).dispatchEvent(new Event('error')));
  await expect(dialog.getByRole('alert')).toContainText('Could not play this sample');
  await dialog.getByRole('tab',{name:/Ghunnah/}).click();
  await page.screenshot({path:'test-results/tajweed-guide-dark.png'});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(900,740));
  expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await page.screenshot({path:'test-results/tajweed-guide-compact.png'});
  await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);
  await page.getByRole('link',{name:'Settings',exact:true}).click();await page.getByRole('button',{name:'Light',exact:true}).click();
  await page.getByRole('link',{name:'Reciters',exact:true}).click();await openProfile('Mohammed Ayyub');
  await expect(page.getByRole('heading',{name:'Mohammed Ayyub',exact:true})).toBeInViewport();
  await page.screenshot({path:'test-results/reciter-profile-light.png'});
  await page.getByRole('link',{name:'Read Quran',exact:true}).click();
  await page.getByRole('button',{name:'Interactive Tajweed & Pronunciation Guide',exact:true}).click();
  await expect(dialog).toBeVisible();
  await page.screenshot({path:'test-results/tajweed-guide-light.png'});
  const ghunnah=await dialog.getByRole('tab',{name:/Ghunnah/}).locator('.tajweed-dot').evaluate(el=>getComputedStyle(el).backgroundColor);
  const madd=await dialog.getByRole('tab',{name:/Madd/}).locator('.tajweed-dot').evaluate(el=>getComputedStyle(el).backgroundColor);
  await page.keyboard.press('Escape');await page.getByLabel('Reading view').selectOption('tajweed');
  await expect(page.locator('.tajweed-g')).toBeVisible();
  expect(await page.locator('.tajweed-g').evaluate(el=>getComputedStyle(el).color)).toBe(ghunnah);
  expect(await page.locator('.tajweed-n').evaluate(el=>getComputedStyle(el).color)).toBe(madd);
  expect(errors).toEqual([]);
 }finally{await app.close();await fs.rm(profile,{recursive:true,force:true});}
});
